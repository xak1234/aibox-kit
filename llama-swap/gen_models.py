#!/usr/bin/env python3
"""Keep the llama-swap model list in step with the GGUF files on the box.

    python3 gen_models.py [--apply] [--quiet]

Scans the model folders (AIBOX_MODELS), writes one entry per loadable GGUF between the AUTO-GENERATED
markers in the llama-swap config, and leaves hand-written entries alone. Only writes when something
changed (llama-swap runs with -watch-config and reloads on a change). Files still being copied are ignored.
A single mmproj file next to a model is paired with it as its vision projector.
"""
import os
import re
import shutil
import subprocess
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lib"))
import aibox_conf as AC  # noqa: E402

CFG = AC.get("AIBOX_SWAP_CONFIG")
INBOX = AC.inbox()
ROOTS = list(dict.fromkeys([INBOX] + AC.model_roots()))
MAX_GB = AC.num("AIBOX_MAX_MODEL_GB", 0) or AC.model_budget_gb()
CTX = int(AC.num("AIBOX_CTX", 32768))
SETTLE_S = 20                      # ignore files modified in the last 20 s (still copying)
SKIP_PATTERNS = ("mmproj", "rerank", "embed", "bge-", "flux", "t5xxl", "t5-xxl", "-mtp-only", "draft")
BEGIN = "  # BEGIN AUTO-GENERATED by gen_models.py (edit the generator, not this block)"
END = "  # END AUTO-GENERATED"
LIB_DIR = os.path.dirname(AC.get("AIBOX_LLAMA_SERVER"))

apply, quiet = "--apply" in sys.argv, "--quiet" in sys.argv


def say(*a):
    if not quiet:
        print(*a)


def root_ok(r):
    """A root under /mnt or /media only counts if a real filesystem is mounted there (an unplugged drive
    leaves an empty mount point; regenerating from it would drop every entry on that drive)."""
    try:
        if not os.path.isdir(r):
            return False
        os.listdir(r)
    except OSError:
        return False
    if not r.startswith(("/mnt/", "/media/")):
        return True
    p = r
    while p != "/" and not os.path.ismount(p):
        p = os.path.dirname(p)
    return p != "/"


missing = [r for r in ROOTS if not root_ok(r)]
avail = [r for r in ROOTS if root_ok(r)]
if missing:
    say("model folder(s) not available; keeping their existing entries:", ", ".join(missing))

try:
    orig = open(CFG, encoding="utf-8").read()
except OSError:
    sys.exit("no llama-swap config at %s (install.sh writes it)" % CFG)
if BEGIN not in orig or END not in orig:
    sys.exit("the AUTO-GENERATED markers are missing from %s" % CFG)
m_auto = re.search(re.escape(BEGIN) + r"\n(.*?)" + re.escape(END), orig, re.S)
auto_prev = m_auto.group(1) if m_auto else ""
hand = orig.replace(m_auto.group(0), "") if m_auto else orig

served_paths = set(re.findall(r"-m (\S+\.gguf)", hand))
served_names = {os.path.basename(p) for p in served_paths}
now = time.time()
found, skipped, seen = [], [], set()
for root in avail:
    for dp, dn, fn in os.walk(root, followlinks=False):
        dn[:] = sorted(d for d in dn if not d.startswith("."))      # .partial and friends
        rp = os.path.realpath(dp)
        if rp in seen:
            continue
        seen.add(rp)
        for f in sorted(fn):
            if not f.lower().endswith(".gguf"):
                continue
            p = os.path.join(dp, f)
            low = p.lower()
            if re.search(r"-0000[2-9]-of-|-000[1-9][0-9]-of-", f):   # later shards
                continue
            if any(s in os.path.basename(low) for s in SKIP_PATTERNS):
                skipped.append((p, "not a chat model"))
                continue
            if " " in p or '"' in p:
                skipped.append((p, "space or quote in path"))
                continue
            try:
                if now - os.path.getmtime(p) < SETTLE_S or os.path.exists(p + ".aria2") or os.path.exists(p + ".part"):
                    skipped.append((p, "still being written"))
                    continue
                size = os.path.getsize(p)
                ms = re.match(r"(.*)-00001-of-(\d{5})\.gguf$", f)
                if ms:
                    size = sum(os.path.getsize(os.path.join(dp, x)) for x in os.listdir(dp)
                               if x.startswith(ms.group(1)) and x.endswith(".gguf"))
            except OSError:
                continue
            if MAX_GB and size > MAX_GB * 1e9:
                skipped.append((p, "%.0f GB, too big for this box (limit %.0f GB)" % (size / 1e9, MAX_GB)))
                continue
            if p in served_paths or f in served_names:
                continue
            served_names.add(f)
            found.append((p, size))


def slug(s):
    return re.sub(r"[^a-z0-9._-]+", "-", s.lower()).strip("-")


ids, entries = {}, []
for p, size in found:
    stem = re.sub(r"-00001-of-\d{5}$", "", os.path.basename(p)[:-5])
    i = slug(stem)
    if i in ids:
        i = slug(os.path.basename(os.path.dirname(p))) + "-" + i
    ids[i] = p
    entries.append((i, p, size))


def mmproj_for(p):
    d = os.path.dirname(p)
    if os.path.realpath(d) in {os.path.realpath(r) for r in ROOTS}:
        return ""                     # loose files in a top-level folder: a lone mmproj there is ambiguous
    try:
        mm = [x for x in os.listdir(d) if "mmproj" in x.lower() and x.lower().endswith(".gguf")]
    except OSError:
        return ""
    return " --mmproj %s" % os.path.join(d, mm[0]) if len(mm) == 1 else ""


block = BEGIN + "\n"
for i, p, size in sorted(entries):
    block += ('  "%s":\n    cmd: "${llama} -m %s%s -c %d ${common_auto}"\n    env:\n      - "LD_LIBRARY_PATH=%s"\n'
              % (i, p, mmproj_for(p), CTX, LIB_DIR))
if missing and auto_prev:
    # entries on a folder that is unplugged right now stay as they were
    for ch in re.split(r'(?m)(?=^  "[^"]+":\n)', auto_prev):
        mm = re.search(r"-m (\S+\.gguf)", ch)
        idm = re.match(r'  "([^"]+)":', ch)
        if ch.strip() and mm and any(mm.group(1).startswith(r.rstrip("/") + "/") for r in missing):
            if idm and idm.group(1) in ids:
                continue
            if idm:
                ids[idm.group(1)] = mm.group(1)
            block += ch if ch.endswith("\n") else ch + "\n"
block += END
new = orig.replace(m_auto.group(0), block, 1)

say("%d auto entries, %d skipped" % (len(entries), len(skipped)))
if not quiet:
    for i, p, size in sorted(entries):
        say("  + %-58s %5.1f GB%s" % (i, size / 1e9, "  (+vision)" if mmproj_for(p) else ""))
    for p, why in skipped:
        if "still being written" in why or "too big" in why or "space" in why:
            say("  - %s: %s" % (os.path.basename(p)[:60], why))

if new == orig:
    say("config unchanged")
elif apply:
    tmp = CFG + ".new"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(new)
    exe = AC.get("AIBOX_LLAMA_SWAP")
    if os.access(exe, os.X_OK):
        v = subprocess.run([exe, "-config", tmp, "-validate"], capture_output=True, text=True)
        out = (v.stdout + v.stderr).strip()
        if v.returncode != 0 and "flag provided but not defined" not in out:
            os.unlink(tmp)
            print("config NOT written - llama-swap rejects it:", out[:400])
            sys.exit(1)
    bak = os.path.join(os.path.dirname(CFG), "backups")
    os.makedirs(bak, exist_ok=True)
    shutil.copy(CFG, os.path.join(bak, "config.yaml." + time.strftime("%Y%m%d-%H%M%S")))
    olds = sorted(x for x in os.listdir(bak) if x.startswith("config.yaml."))
    for x in olds[:-20]:                                             # keep the last 20 versions
        os.unlink(os.path.join(bak, x))
    os.replace(tmp, CFG)
    print("config updated:", ", ".join(sorted(ids)) if len(ids) < 6 else "%d models" % len(ids))
else:
    say("config would change (dry run)")
